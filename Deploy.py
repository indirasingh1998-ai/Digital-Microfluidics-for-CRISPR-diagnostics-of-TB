# =======================================================
#        Post-fusion NMS: keep highest score only
# =======================================================
def iou_xyxy(a, b):
    # a, b are [x1,y1,x2,y2] in pixels
    xA = max(a[0], b[0])
    yA = max(a[1], b[1])
    xB = min(a[2], b[2])
    yB = min(a[3], b[3])

    inter_w = max(0, xB - xA)
    inter_h = max(0, yB - yA)
    inter = inter_w * inter_h

    area_a = max(0, a[2] - a[0]) * max(0, a[3] - a[1])
    area_b = max(0, b[2] - b[0]) * max(0, b[3] - b[1])

    union = area_a + area_b - inter + 1e-9
    return inter / union


def nms_keep_highest(boxes, scores, labels, iou_thr=0.5):
    """
    Class-agnostic NMS: for overlapping boxes, keep only the highest score.
    boxes:  list of [x1,y1,x2,y2] (pixels)
    scores: list of floats
    labels: list of ints
    """
    if len(boxes) == 0:
        return [], [], []

    order = sorted(range(len(scores)), key=lambda i: scores[i], reverse=True)
    keep = []

    while order:
        best = order.pop(0)
        keep.append(best)

        remaining = []
        for j in order:
            if iou_xyxy(boxes[best], boxes[j]) <= iou_thr:
                remaining.append(j)
        order = remaining

    boxes_kept = [boxes[i] for i in keep]
    scores_kept = [scores[i] for i in keep]
    labels_kept = [labels[i] for i in keep]
    return boxes_kept, scores_kept, labels_kept


