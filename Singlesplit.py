import pandas as pd
import os

label_dir = "/content/runs/segment/predict2/labels"

rows = []

for file in os.listdir(label_dir):
    path = os.path.join(label_dir, file)
    if os.path.getsize(path) == 0:
        rows.append([file, "no_detection"])
    else:
        with open(path) as f:
            lines = f.readlines()
            for line in lines:
                cls = line.split()[0]
                conf = line.split()[1]
                rows.append([file, cls, conf])

df = pd.DataFrame(rows, columns=["image", "class", "confidence"])
